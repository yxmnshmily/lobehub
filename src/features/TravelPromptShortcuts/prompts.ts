type PromptSeed = readonly [title: string, focus: string];

const promptGroup = (
  title: string,
  icon: typeof PencilLine,
  context: string,
  facts: string,
  seeds: readonly PromptSeed[],
) => ({
  icon,
  title,
  prompts: seeds.map(
    ([promptTitle, focus]) =>
      [
        promptTitle,
        `请参考当前栏目已有的${context}案例，${focus}。先向我确认${facts}，只使用我提供或确认的真实信息，不虚构价格、行程和亲身经历。`,
      ] as const,
  ),
});

